console.log(str.slice(1,5)); // Output: AVAS

// SPLIT(): It splits a string into an array of substrings based on a specified separator and returns the new array. It does not modify the original string.

let str1 = "Hello, World!";
console.log(str1);
console.log(str1.split(" "));

// IndexOf(): It returns the index of the first occurrence of a specified value in a string. If the value is not found, it returns -1. It does not modify the original string.

let str2 = "Hello, World!";
console.log(str2);
console.log(str2.indexOf("World"));